/** The same config with a «_راهنما» line after every key. */
export function withHelp(cfg) {
  const out = {};
  for (const [group, value] of Object.entries(cfg)) {
    if (group.startsWith('_') || typeof value !== 'object' || value === null) {
      if (!group.startsWith('_')) out[group] = value;
      continue;
    }
    const h = HELP[group] || {};
    const g = {};
    if (h._title) g['_راهنمای_بخش'] = h._title;
    for (const [k, v] of Object.entries(value)) {
      if (k.startsWith('_')) continue;
      g[k] = v;
      if (h[k]) g[`_راهنما_${k}`] = h[k];
    }
    out[group] = g;
  }
  return out;
}
